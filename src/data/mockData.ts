const SENSOR_POINTS = 30
const SENSOR_STEP_DAYS = 2

export const DEFAULT_THRESHOLDS: Thresholds = {
  healthWarning: 70,
  healthCritical: 40,
  riskWarning: 50,
  riskCritical: 70,
}

function s(
  name: string,
  unit: string,
  value: number,
  min: number,
  max: number,
  level: SensorLevel,
  trend: 'up' | 'down' | 'flat'
): SensorReading {
  return { name, unit, value, min, max, level, trend }
}

function buildMachine(
  id: string,
  name: string,
  type: string,
  _status: MachineStatus,
  _healthScore: number,
  _failureRisk: number,
  maintenanceStatus: string,
  _recommendation: string,
  _likelihood: string,
  location: string,
  manufacturer: string,
  model: string,
  installationDate: string,
  description: string,
  sensors: SensorReading[],
  events: [number, EventMarker['type'], string][],
  lastMaintenanceDaysAgo: number,
  nextMaintenanceInDays: number,
  seed: number,
  custom = false
): Machine {
  const rnd = seededRandom(seed)
  const sensorHistory: SensorSeries[] = sensors.map((sensor) => {
    const amplitude = ((sensor.max - sensor.min) * 0.12) / 2
    return {
      name: sensor.name,
      unit: sensor.unit,
      data: Array.from({ length: SENSOR_POINTS }, (_, index) => {
        const date = daysAgo((SENSOR_POINTS - index - 1) * SENSOR_STEP_DAYS)
        const progress = index / (SENSOR_POINTS - 1)
        const value =
          index === SENSOR_POINTS - 1
            ? sensor.value
            : sensor.min +
              (sensor.value - sensor.min) * progress +
              (rnd() - 0.5) * amplitude
        return { date, value: Number(value.toFixed(2)) }
      }),
    }
  })
  const eventMarkers: EventMarker[] = events.map(([ago, type, note]) => ({
    date: daysAgo(ago),
    type,
    note,
    isDemo: true,
  }))

  return {
    id,
    name,
    type,
    status: null,
    healthScore: null,
    failureRisk: null,
    maintenanceStatus,
    recommendation: null,
    likelihood: null,
    location,
    manufacturer,
    model,
    installationDate,
    lastMaintenance: daysAgo(lastMaintenanceDaysAgo),
    nextMaintenance: new Date(
      Date.now() + nextMaintenanceInDays * 86_400_000
    ).toISOString(),
    description,
    sensors,
    history: [],
    sensorHistory,
    events: eventMarkers,
    custom,
    modelTypeCode: machineTypeCode(type),
    predictionStatus: 'loading',
    predictionInputs: simulateMachineInputs(id, type),
  }
}

